/* eslint-disable no-console */
/**
 * Writes app/(protected)/(cards)/cards/index.generated.ts: one import per card
 * file under cards/. Runs by itself before `yarn dev`, `yarn build` and
 * `yarn test`, so adding a card is only creating its file (and its image).
 *
 * Usage: yarn cards:index         (writes the index)
 *        yarn cards:index --check (fails when it is out of date)
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const CARDS_DIR = path.join(process.cwd(), 'app', '(protected)', '(cards)', 'cards')
const INDEX_FILE = path.join(CARDS_DIR, 'index.generated.ts')
const IMPORT_ROOT = '@/app/(protected)/(cards)/cards'

function cardFiles(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const full = path.join(dir, name)

      if (statSync(full).isDirectory()) {
        return cardFiles(full)
      }

      return name.endsWith('.ts') && full !== INDEX_FILE ? [full] : []
    })
}

export function renderIndex(): string {
  const files = cardFiles(CARDS_DIR).map((file) =>
    path.relative(CARDS_DIR, file).replace(/\\/g, '/').replace(/\.ts$/, '')
  )
  const imports = files.map((file, index) => `import card${index} from '${IMPORT_ROOT}/${file}'`)

  return [
    '/* eslint-disable simple-import-sort/imports */',
    '// Generated by `yarn cards:index` from the files of this folder. Do not edit it by hand.',
    "import { CardDefinition } from '@/app/(protected)/(engine)/models/CardDefinition'",
    ...imports,
    '',
    '/** Every card of the game, with the path of its file (relative to this folder). */',
    'export const CARD_FILES: { file: string; card: CardDefinition }[] = [',
    files.map((file, index) => `  { file: '${file}', card: card${index} }`).join(',\n'),
    ']',
    ''
  ].join('\n')
}

if (require.main === module) {
  const content = renderIndex()
  let current = ''

  try {
    current = readFileSync(INDEX_FILE, 'utf-8')
  } catch {}

  if (process.argv.includes('--check')) {
    if (current !== content) {
      console.error('The card index is out of date: run `yarn cards:index`.')
      process.exit(1)
    }
  } else if (current !== content) {
    writeFileSync(INDEX_FILE, content)
    console.log(
      `Card index written (${content.split('\n').filter((line) => line.startsWith('import card')).length} cards).`
    )
  }
}
