import { BaseEntity, Column, Entity, Serializable } from '@neogroup/neorm'
import { Locale } from '@/app/i18n/config'
import { getUserDisplayName } from '@/app/utils/users'

/** A ChronoCast player. Signs in with Google or with email + password (verified by email). */
@Entity({ table: 'users' })
export class User extends BaseEntity {
  @Column({ primaryKey: true, autoGenerated: true })
  id!: number

  @Column()
  email!: string

  /** Null for accounts created through Google (they never set a password). */
  @Column()
  passwordHash!: string | null

  /** Player name shown in the game (HUD, summaries). */
  @Column()
  name!: string | null

  /** Last name, shown next to the name. Null: never set (filled from Google on sign-in); '': cleared by the player. */
  @Column()
  lastName!: string | null

  /** Nickname: when set, shown instead of the name and last name. */
  @Column()
  nickname!: string | null

  /** True when the user verified their email address. Always true for Google-authenticated users. */
  @Column({ cast: 'boolean' })
  emailVerified!: boolean

  /** Language chosen by the player (app and emails). */
  @Column()
  locale!: Locale

  /** False disables the account's login. */
  @Column({ cast: 'boolean' })
  active!: boolean

  /** Prestige: the Elo-like rating of public PvP matches (starts at 1200). */
  @Column({ cast: 'number' })
  rating!: number

  /** Gold to spend in the shop. */
  @Column({ cast: 'number' })
  gold!: number

  /** Total experience earned in battles. */
  @Column({ cast: 'number' })
  xp!: number

  /** Level of the experience (1 up): opens the rarities of the shop. */
  @Column({ cast: 'number' })
  level!: number

  /** The starter hero chosen on the first visit (null: not chosen yet, the player goes to /welcome). */
  @Column()
  starterHeroId!: string | null

  /** Packs opened in a row without a legendary card (the guarantee of the shop). */
  @Column({ cast: 'number' })
  packsWithoutLegendary!: number

  /** When the player last won a public match (epoch ms, read raw): the first win of the day pays extra. */
  @Column()
  lastWinAt!: string | number | null

  /** Public PvP matches played (the ranking lists the players with at least one). */
  @Column({ cast: 'number' })
  pvpMatches!: number

  @Column({ cast: 'date' })
  createdAt!: Date

  @Serializable()
  get displayName(): string {
    return getUserDisplayName(this)
  }
}
